public class ShortcutTests
{
    [Theory]
    [InlineData("Alt+Space", "Alt+Space")]
    [InlineData("alt+space", "Alt+Space")]
    [InlineData("Win+Shift+Space", "Shift+Win+Space")]
    [InlineData("Ctrl+Shift+P", "Ctrl+Shift+P")]
    [InlineData("control + alt + delete", "Ctrl+Alt+Delete")]
    [InlineData("Ctrl+1", "Ctrl+1")]
    [InlineData("Win+F5", "Win+F5")]
    [InlineData("Ctrl+Esc", "Ctrl+Escape")]
    [InlineData("F12", "F12")]
    [InlineData("Alt+Return", "Alt+Enter")]
    public void ReadableShortcuts_AreParsed_AndPrintedInAFixedOrder(string text, string expected)
    {
        Assert.True(Shortcut.TryParse(text, out var shortcut));
        Assert.Equal(expected, shortcut!.ToString());
    }

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("   ")]
    [InlineData("Alt+")]
    [InlineData("+Space")]
    [InlineData("Alt++Space")]
    [InlineData("Alt+Alt+Space")]
    [InlineData("Alt+Banana")]
    [InlineData("Banana+Space")]
    [InlineData("Alt+Shift")]
    [InlineData("Alt+Ctrl")]
    [InlineData("Space+Alt")]
    public void NonsenseShortcuts_AreRefused(string? text)
    {
        Assert.False(Shortcut.TryParse(text, out var shortcut));
        Assert.Null(shortcut);
    }

    [Fact]
    public void Sending_HoldsTheModifiers_TapsTheKey_AndReleasesInReverse()
    {
        var injector = new FakeInjector();
        Assert.True(Shortcut.TryParse("Win+Shift+Space", out var shortcut));

        shortcut!.Send(injector);

        Assert.Equal(["key 5B down", "key A0 down", "key 20 down", "key 20 up", "key A0 up", "key 5B up"], injector.Events);
    }

    [Fact]
    public void Sending_AloneKey_JustTapsIt()
    {
        var injector = new FakeInjector();
        Assert.True(Shortcut.TryParse("F5", out var shortcut));

        shortcut!.Send(injector);

        Assert.Equal(["key 74 down", "key 74 up"], injector.Events);
    }

    [Fact]
    public void ASendThatFailsHalfway_StillReleasesTheModifiers()
    {
        var injector = new ThrowingInjector(throwOnKeyDownNumber: 2);
        Assert.True(Shortcut.TryParse("Ctrl+Alt+Space", out var shortcut));

        Assert.Throws<InvalidOperationException>(() => shortcut!.Send(injector));

        // Ctrl went down; Alt failed while going down. Both are released anyway, because a press that
        // failed halfway may still have taken effect, and a stuck modifier is worse than a spare release.
        Assert.Equal([0xA2], injector.Downs);
        Assert.Equal([0xA4, 0xA2], injector.Ups); // reverse order: Alt, then Ctrl
    }

    private sealed class ThrowingInjector(int throwOnKeyDownNumber) : IInputInjector
    {
        private int _downCount;

        public List<int> Downs { get; } = [];

        public List<int> Ups { get; } = [];

        public void MoveRelative(int dx, int dy) { }

        public void MouseButton(MouseButton button, bool down) { }

        public void Wheel(int vertical, int horizontal) { }

        public void TypeText(string text) { }

        public void Key(KeyInfo key, bool down)
        {
            if (!down)
            {
                Ups.Add(key.VirtualKey);
                return;
            }

            if (++_downCount == throwOnKeyDownNumber)
            {
                throw new InvalidOperationException("boom");
            }

            Downs.Add(key.VirtualKey);
        }
    }
}

