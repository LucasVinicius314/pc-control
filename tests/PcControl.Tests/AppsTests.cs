public class AppIdTests
{
    [Fact]
    public void TheSameLaunchId_AlwaysGivesTheSameId()
    {
        Assert.Equal(AppId.From("Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"), AppId.From("Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"));
    }

    [Fact]
    public void DifferentLaunchIds_GiveDifferentIds()
    {
        Assert.NotEqual(AppId.From(@"D:\Program Files\7-Zip\7zFM.exe"), AppId.From(@"D:\Program Files\7-Zip\7-zip.chm"));
    }

    [Theory]
    [InlineData("steam://rungameid/1473350")]
    [InlineData(@"{7C5A40EF-A0FB-4BFC-874A-C0F2E0B9FA8E}\VB\Voicemeeter\VoicemeeterBUSGEQ15.exe")]
    [InlineData("Microsoft.AutoGenerated.{3D1591B6-092C-B25C-4E52-6930A22606BC}")]
    [InlineData("anilist.co-C27BEC46_c49w0cd8j5at2!App")]
    public void RealWorldLaunchIds_BecomeShortSafeIds(string launchId)
    {
        var id = AppId.From(launchId);

        Assert.Equal(AppId.Length, id.Length);
        Assert.True(AppId.LooksValid(id));
        Assert.DoesNotContain(launchId, id, StringComparison.Ordinal);
    }

    [Theory]
    [InlineData(null)]
    [InlineData("")]
    [InlineData("0123456789abcde")] // too short
    [InlineData("0123456789abcdef0")] // too long
    [InlineData("0123456789ABCDEF")] // upper case
    [InlineData("0123456789abcdeg")]
    [InlineData("../../windows/sys")]
    [InlineData("steam://rungameid/1")]
    public void OnlyHashLikeIds_AreAccepted(string? id)
    {
        Assert.False(AppId.LooksValid(id));
    }

    [Fact]
    public void NoLaunchId_IsRefused()
    {
        Assert.Throws<ArgumentException>(() => AppId.From(string.Empty));
    }
}

public sealed class FakeCatalog : IAppCatalog
{
    public List<AppEntry> Apps { get; set; } = [];

    public bool LaunchSucceeds { get; set; } = true;

    public List<string> Launched { get; } = [];

    public int Reads { get; private set; }

    public byte[]? Icon { get; set; } = [0x89, 0x50, 0x4E, 0x47];

    public IReadOnlyList<AppEntry> GetApps()
    {
        Reads++;
        return Apps;
    }

    public byte[]? GetIconPng(AppEntry app, int size) => Icon;

    public bool Launch(AppEntry app)
    {
        Launched.Add(app.LaunchId);
        return LaunchSucceeds;
    }
}

public sealed class MemoryStateStore : IAppsStateStore
{
    public AppsState State { get; set; } = AppsState.Empty;

    public int Saves { get; private set; }

    public AppsState Load() => State;

    public void Save(AppsState state)
    {
        State = state;
        Saves++;
    }
}

public class AppsServiceTests
{
    private readonly FakeCatalog _catalog = new();
    private readonly MemoryStateStore _store = new();
    private readonly FakeTimeProvider _time = new();

    public AppsServiceTests()
    {
        _catalog.Apps =
        [
            AppEntry.Create("Notepad", "notepad"),
            AppEntry.Create("calculator", "calc"),
            AppEntry.Create("Chrome", "chrome"),
            AppEntry.Create("Édge", "edge"),
        ];
    }

    private AppsService Service(int recentLimit = 20) => new(_catalog, _store, _time, recentLimit);

    private static string IdOf(string launchId) => AppId.From(launchId);

    [Fact]
    public void TheList_IsAlphabetical_IgnoringCase()
    {
        var names = Service().GetList().Apps.Select(a => a.Name);

        Assert.Equal(["calculator", "Chrome", "Édge", "Notepad"], names);
    }

    [Fact]
    public void EveryAppGetsItsStableId()
    {
        var list = Service().GetList();

        Assert.All(list.Apps, a => Assert.True(AppId.LooksValid(a.Id)));
        Assert.Contains(list.Apps, a => a.Id == IdOf("notepad") && a.Name == "Notepad");
    }

    [Fact]
    public void TwoAppsWithTheSameName_AreBothListed_WithDifferentIds()
    {
        _catalog.Apps = [AppEntry.Create("Setup", "a"), AppEntry.Create("Setup", "b")];

        var list = Service().GetList();

        Assert.Equal(2, list.Apps.Count);
        Assert.NotEqual(list.Apps[0].Id, list.Apps[1].Id);
    }

    [Fact]
    public void TheSameLaunchIdTwice_IsListedOnce()
    {
        _catalog.Apps = [AppEntry.Create("Notepad", "notepad"), AppEntry.Create("Notepad (2)", "notepad")];

        Assert.Single(Service().GetList().Apps);
    }

    [Fact]
    public void EntriesWithoutAName_AreLeftOut()
    {
        _catalog.Apps = [AppEntry.Create("", "x"), AppEntry.Create("   ", "y"), AppEntry.Create("Real", "z")];

        Assert.Equal(["Real"], Service().GetList().Apps.Select(a => a.Name));
    }

    [Fact]
    public void Launching_StartsTheApp_AndRemembersIt()
    {
        var service = Service();

        var result = service.Launch(IdOf("calc"));

        Assert.Equal(LaunchOutcome.Ok, result.Outcome);
        Assert.Equal("calculator", result.App!.Name);
        Assert.Equal(["calc"], _catalog.Launched);
        Assert.Equal([IdOf("calc")], service.GetList().Recent);
    }

    [Fact]
    public void Recent_IsNewestFirst_WithoutDuplicates()
    {
        var service = Service();

        service.Launch(IdOf("calc"));
        service.Launch(IdOf("chrome"));
        service.Launch(IdOf("calc"));

        Assert.Equal([IdOf("calc"), IdOf("chrome")], service.GetList().Recent);
    }

    [Fact]
    public void Recent_IsLimited()
    {
        var service = Service(recentLimit: 2);

        service.Launch(IdOf("calc"));
        service.Launch(IdOf("chrome"));
        service.Launch(IdOf("edge"));

        Assert.Equal([IdOf("edge"), IdOf("chrome")], service.GetList().Recent);
    }

    [Fact]
    public void AnAppThatFailsToStart_IsNotRemembered()
    {
        _catalog.LaunchSucceeds = false;
        var service = Service();

        var result = service.Launch(IdOf("calc"));

        Assert.Equal(LaunchOutcome.Failed, result.Outcome);
        Assert.Empty(service.GetList().Recent);
        Assert.Equal(0, _store.Saves);
    }

    [Theory]
    [InlineData("0000000000000000")]
    [InlineData("notepad")]
    [InlineData("")]
    [InlineData(null)]
    [InlineData("steam://rungameid/1")]
    public void UnknownIds_AreRefused_AndNothingIsStarted(string? id)
    {
        var result = Service().Launch(id);

        Assert.Equal(LaunchOutcome.UnknownApp, result.Outcome);
        Assert.Empty(_catalog.Launched);
    }

    [Fact]
    public void ARawLaunchId_CannotBeUsedInPlaceOfTheId()
    {
        // The phone must never be able to hand the shell its own string.
        var result = Service().Launch("notepad");

        Assert.Equal(LaunchOutcome.UnknownApp, result.Outcome);
    }

    [Fact]
    public void Favorites_CanBeSetAndCleared()
    {
        var service = Service();

        Assert.True(service.SetFavorite(IdOf("chrome"), true));
        Assert.Equal(["Chrome"], service.GetList().Apps.Where(a => a.Favorite).Select(a => a.Name));

        Assert.True(service.SetFavorite(IdOf("chrome"), false));
        Assert.DoesNotContain(service.GetList().Apps, a => a.Favorite);
    }

    [Fact]
    public void MarkingAFavoriteTwice_DoesNotDuplicateIt()
    {
        var service = Service();

        service.SetFavorite(IdOf("chrome"), true);
        service.SetFavorite(IdOf("chrome"), true);

        Assert.Single(_store.State.Favorites);
    }

    [Fact]
    public void AnUnknownAppCannotBeFavorited()
    {
        Assert.False(Service().SetFavorite("0000000000000000", true));
        Assert.Equal(0, _store.Saves);
    }

    [Fact]
    public void FavoritesAndRecent_SurviveARestart()
    {
        var first = Service();
        first.SetFavorite(IdOf("edge"), true);
        first.Launch(IdOf("calc"));

        var second = Service();
        var list = second.GetList();

        Assert.True(list.Apps.Single(a => a.Name == "Édge").Favorite);
        Assert.Equal([IdOf("calc")], list.Recent);
    }

    [Fact]
    public void AnUninstalledApp_DropsOutOfRecent_ButItsFavoriteIsKept()
    {
        var service = Service();
        service.SetFavorite(IdOf("edge"), true);
        service.Launch(IdOf("edge"));

        _catalog.Apps = _catalog.Apps.Where(a => a.LaunchId != "edge").ToList();
        _time.Advance(TimeSpan.FromMinutes(1));

        Assert.DoesNotContain(IdOf("edge"), service.GetList().Recent);

        _catalog.Apps.Add(AppEntry.Create("Édge", "edge")); // reinstalled
        _time.Advance(TimeSpan.FromMinutes(1));
        Assert.True(service.GetList().Apps.Single(a => a.Name == "Édge").Favorite);
    }

    [Fact]
    public void TheStartMenu_IsReadAgainOnlyAfterTheCacheExpires()
    {
        var service = Service();

        service.GetList();
        service.GetList();
        Assert.Equal(1, _catalog.Reads);

        _time.Advance(TimeSpan.FromSeconds(4));
        _catalog.Apps.Add(AppEntry.Create("New app", "new"));

        Assert.Contains(service.GetList().Apps, a => a.Name == "New app");
        Assert.Equal(2, _catalog.Reads);
    }

    [Fact]
    public void Icons_AreLookedUpByTheSameIds()
    {
        var service = Service();

        Assert.Equal(_catalog.Icon, service.GetIcon(IdOf("calc"), 64));
        Assert.Null(service.GetIcon("0000000000000000", 64));
    }

    [Theory]
    [InlineData(0)]
    [InlineData(AppsService.MaxRecent + 1)]
    public void TheRecentLimit_MustBeSensible(int limit)
    {
        Assert.Throws<ArgumentOutOfRangeException>(() => Service(limit));
    }
}

