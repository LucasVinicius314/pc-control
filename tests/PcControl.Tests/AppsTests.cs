public class KeyCatalogReverseTests
{
    [Theory]
    [InlineData(0x20, "Space")]
    [InlineData(0x41, "KeyA")]
    [InlineData(0x30, "Digit0")]
    [InlineData(0x70, "F1")]
    [InlineData(0x0D, "Enter")]
    [InlineData(0x10, "ShiftLeft")]
    [InlineData(0x11, "ControlLeft")]
    [InlineData(0x12, "AltLeft")]
    [InlineData(0xA0, "ShiftLeft")]
    [InlineData(0xA1, "ShiftRight")]
    public void VirtualKeys_MapBackToCatalogNames(int vk, string expected)
    {
        Assert.True(KeyCatalog.TryGetByVirtualKey((ushort)vk, out var name));
        Assert.Equal(expected, name);
    }

    [Theory]
    [InlineData(0x03)]
    [InlineData(0x00)]
    [InlineData(0xFF)]
    public void UnknownVirtualKeys_AreRefused(int vk)
    {
        Assert.False(KeyCatalog.TryGetByVirtualKey((ushort)vk, out _));
    }

    [Fact]
    public void EveryCatalogKey_RoundTrips()
    {
        foreach (var name in KeyCatalog.Names)
        {
            KeyCatalog.TryGet(name, out var key);
            Assert.True(KeyCatalog.TryGetByVirtualKey(key.VirtualKey, out var back));

            // Left and right variants share nothing, so each name maps to itself or its left-hand twin.
            Assert.True(back == name || back.Replace("Left", "Right", StringComparison.Ordinal) == name || back == name.Replace("Right", "Left", StringComparison.Ordinal),
                $"{name} -> {key.VirtualKey:X2} -> {back}");
        }
    }
}

